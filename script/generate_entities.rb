# frozen_string_literal: true

# Regenerates lib/zat/markdown/entities.rb from the WHATWG list.
require "json"
require "open-uri"

SOURCE = "https://html.spec.whatwg.org/entities.json"
OUT = File.expand_path("../lib/zat/markdown/entities.rb", __dir__)

# CommonMark only recognizes the forms that end in ";".
entities = JSON.parse(URI(SOURCE).read)
  .filter_map { |name, entity| [name[1..-2], entity["codepoints"]] if name.end_with?(";") }
  .sort

lines = entities.map do |name, codepoints|
  %(      "#{name}" => "#{codepoints.map { format("\\u{%X}", it) }.join}",)
end

File.write(OUT, <<~RUBY)
  # frozen_string_literal: true

  # Generated by script/generate_entities.rb from #{SOURCE}
  # (WHATWG, CC BY 4.0). Do not edit by hand.
  module Zat
    module Markdown
      ENTITIES = Ractor.make_shareable({
  #{lines.join("\n").chomp(",")}
      })
    end
  end
RUBY
puts "#{entities.size} entities written to #{OUT}"
